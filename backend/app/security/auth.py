"""Security: Argon2id password hashing, JWT access + rotating refresh tokens, CSRF, current-user dependency."""
from datetime import UTC, datetime, timedelta
from uuid import uuid4

from fastapi import Depends, HTTPException, Request, status
from fastapi.security import OAuth2PasswordBearer
from jose import JWTError, jwt
from passlib.context import CryptContext
from sqlmodel import Session, select

from app.core.config import get_settings
from app.core.db import get_session
from app.models.models import User
from app.schemas.schemas import TokenResponse, UserResponse

settings = get_settings()

pwd_context = CryptContext(schemes=["argon2"], deprecated="auto")
oauth2_scheme = OAuth2PasswordBearer(tokenUrl="/api/auth/signin", auto_error=False)


def hash_password(password: str) -> str:
    """Hash password with Argon2id (per-user salt auto-generated by passlib)."""
    return pwd_context.hash(password)


def verify_password(plain_password: str, hashed_password: str) -> bool:
    """Constant-time password verification."""
    return pwd_context.verify(plain_password, hashed_password)


def _encode(payload: dict, minutes: int | None = None, days: int | None = None) -> str:
    now = datetime.now(UTC)
    if minutes is not None:
        expire = now + timedelta(minutes=minutes)
    elif days is not None:
        expire = now + timedelta(days=days)
    else:
        expire = now + timedelta(minutes=settings.access_token_expire_minutes)
    to_encode = {**payload, "iat": now, "exp": expire}
    return jwt.encode(to_encode, settings.jwt_secret, algorithm=settings.algorithm)


def create_access_token(subject: str, email: str, role: str) -> str:
    """Short-lived access token (15 minutes)."""
    return _encode(
        {"sub": subject, "email": email, "role": role, "type": "access"},
        minutes=settings.access_token_expire_minutes,
    )


def create_refresh_token(subject: str, email: str, role: str) -> str:
    """Long-lived refresh token (7 days) — returned to client, hashed before storage."""
    return _encode(
        {"sub": subject, "email": email, "role": role, "type": "refresh"},
        days=settings.refresh_token_expire_days,
    )


def hash_token(token: str) -> str:
    """Hash a raw token for storage (so DB never contains plaintext tokens)."""
    import hashlib

    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def decode_token(token: str, expected_type: str = "access") -> dict:
    try:
        payload = jwt.decode(token, settings.jwt_secret, algorithms=[settings.algorithm])
    except JWTError as err:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or expired token",
            headers={"WWW-Authenticate": "Bearer"},
        ) from err
    if payload.get("type") != expected_type:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=f"Expected {expected_type} token",
            headers={"WWW-Authenticate": "Bearer"},
        )
    return payload


def generate_csrf_token() -> str:
    return uuid4().hex


def verify_csrf_token(request: Request, csrf_token: str | None = None) -> None:
    """Double-submit CSRF check for state-changing requests."""
    if settings.app_env == "production":
        cookie_csrf = request.cookies.get("csrf_token")
        if not cookie_csrf or not csrf_token or cookie_csrf != csrf_token:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="CSRF token mismatch",
            )


def get_current_user(
    request: Request,
    session: Session = Depends(get_session),
) -> User:
    """Resolve the current user from the access_token cookie or Bearer header."""
    token = request.cookies.get("access_token")
    if not token:
        authorization = request.headers.get("authorization", "")
        if authorization.startswith("Bearer "):
            token = authorization[len("Bearer "):]
    if not token:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Not authenticated",
            headers={"WWW-Authenticate": "Bearer"},
        )
    payload = decode_token(token, expected_type="access")
    user_id: str | None = payload.get("sub")
    if user_id is None:
        raise HTTPException(status_code=401, detail="Invalid token")
    user = session.exec(select(User).where(User.user_id == user_id)).first()
    if not user:
        raise HTTPException(status_code=401, detail="User not found")
    if not user.is_active:
        raise HTTPException(status_code=403, detail="Account is deactivated")
    if user.locked_until and user.locked_until > datetime.now(UTC):
        raise HTTPException(status_code=403, detail="Account is locked — try again later")
    return user


def require_role(allowed_roles: list[str]):
    def role_checker(current_user: User = Depends(get_current_user)) -> User:
        if current_user.role not in allowed_roles:
            raise HTTPException(
                status_code=403,
                detail=f"Insufficient permissions — requires one of: {', '.join(allowed_roles)}",
            )
        return current_user
    return role_checker


def tokens_for_user(user: User) -> TokenResponse:
    access = create_access_token(user.user_id, user.email, user.role)
    refresh = create_refresh_token(user.user_id, user.email, user.role)
    return TokenResponse(
        access_token=access,
        refresh_token=refresh,
        user=UserResponse.model_validate(user),
    )
